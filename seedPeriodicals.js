async function seedPeriodicals() {
  try {
    console.log("Connecting to Supabase for Periodicals Seeding...");

    let insertedCount = 0;
    let updatedCount = 0;

    for (const bookData of periodicals) {
      const payload = {
        barcode: bookData.barcode,
        accession_number: bookData.accessionNumber || null,
        title: bookData.title,
        author: bookData.author || "Unknown",
        authors: Array.isArray(bookData.authors) ? bookData.authors : [],
        category: bookData.category || "Periodicals",
        section: bookData.section || "Periodical Section (Includes Journal, Magazine, Leaflets, Brochures, Clippings)",
        shelf: bookData.shelf || "General Shelf",
        publisher: bookData.publisher || "N/A",
        publication_year: bookData.publicationYear ? Number(bookData.publicationYear) : null,
        status: bookData.status || "available",
        available: bookData.available !== false,
        description: bookData.description || "",
        cover_url: bookData.coverUrl || "",
        source: bookData.source || "Misamis Oriental Capitol Public Library",
        condition: bookData.condition || "Good",
        copies: bookData.copies || 1,
        borrowable: bookData.borrowable !== false,
        archived: false,
        updated_at: new Date().toISOString()
      };

      // Check existing by barcode or cover_url
      const { data: existing } = await supabase
        .from("books")
        .select("id")
        .or(`barcode.eq.${bookData.barcode},cover_url.eq.${bookData.coverUrl}`)
        .maybeSingle();

      if (existing) {
        const { error: updateError } = await supabase
          .from("books")
          .update(payload)
          .eq("id", existing.id);

        if (updateError) {
          console.error(`Failed to update ${bookData.title}:`, updateError.message);
        } else {
          updatedCount++;
          console.log(`Updated: ${bookData.title} (${bookData.barcode})`);
        }
      } else {
        const { error: insertError } = await supabase
          .from("books")
          .insert(payload);

        if (insertError) {
          console.error(`Failed to insert ${bookData.title}:`, insertError.message);
        } else {
          insertedCount++;
          console.log(`Inserted: ${bookData.title} (${bookData.barcode})`);
        }
      }
    }

    console.log(`\n🎉 Done! Processed all ${periodicals.length} periodicals.`);
    console.log(`- Inserted new periodicals: ${insertedCount}`);
    console.log(`- Updated existing periodicals: ${updatedCount}`);

    const { count: totalBooks } = await supabase
      .from("books")
      .select("id", { count: "exact", head: true });
    console.log(`Total books currently in Supabase database: ${totalBooks}`);

    process.exit(0);
  } catch (err) {
    console.error("Error seeding periodicals:", err);
    process.exit(1);
  }
}

